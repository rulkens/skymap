/** writeAntiqueEarthRealms — the baked realm label table as `src/data/labels/antiqueEarthRealms.ts`,
 * one row per name, prettier-stable. */

import type { AntiqueEarthRealm } from '../../../../src/@types/rendering/AntiqueEarthRealm';
import { writeFileAtomic } from '../../../utils/io/writeFileAtomic';

export function writeAntiqueEarthRealms(path: string, rows: readonly AntiqueEarthRealm[]): void {
  const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  const lines = rows.map(
    (r) =>
      `  { id: ${q(r.id)}, name: ${q(r.name)}, modern: ${q(r.modern)}, latDeg: ${r.latDeg}, lonDeg: ${r.lonDeg}, rank: ${r.rank}, level: ${r.level} },`,
  );
  const text = `/**
 * ANTIQUE_EARTH_REALMS — the realms and provinces of the antique Earth map's 1690
 * borders, named as an Amsterdam plate of 1690 lettered them. GENERATED by
 * \`npm run build-antique-earth\` (tools/antique/earth/sources/realmsSource.ts)
 * from the realm tables in tools/antique/earth/data/: edit those, then re-bake.
 */

import type { AntiqueEarthRealm } from '../../@types/rendering/AntiqueEarthRealm';

// prettier-ignore
export const ANTIQUE_EARTH_REALMS: readonly AntiqueEarthRealm[] = [
${lines.join('\n')}
];
`;
  writeFileAtomic(path, new TextEncoder().encode(text));
}
